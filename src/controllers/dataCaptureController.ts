// Get lookup values by type
export const getLookupValues = async (req: Request, res: Response) => {
  try {
    const pool = await poolPromise;
    const { type } = req.params;

    console.log(`🔍 Fetching lookup values for type: ${type}`);

    const tableMap: Record<string, string> = {
      'bmi-values': 'BMIINTValues',
      'bp-values': 'BPINTValues',
      'rbs-values': 'RBSINTValues',
      'breast-exam-values': 'BreastExams',
      'pap-smear-values': 'PAPSmears',
      'via-villi-values': 'ViaVillies',
      'fbs-values': 'FBSINTValues',
      'hba1c-values': 'HBA1CINTValues',
      'lipid-values': 'Lipids',
      'microalbumin-values': 'MicroalbuminINTValues',
      'bmd-values': 'BMDINTValues',
      'psa-values': 'PSAINTValues',
      'hepatitis-b-values': 'HepatitisBValues',
      'hepatitis-c-values': 'HepatitisCValues',
      'bp-remark-values': 'BPRemarks',
      'rbs-remark-values': 'RBSRemarks',
      'referral-values': 'Referrals',
    };

    const tableName = tableMap[type];
    if (!tableName) {
      console.log(`❌ Invalid lookup type: ${type}`);
      return res.status(400).json({ 
        success: false, 
        message: 'Invalid lookup type' 
      });
    }

    console.log(`✅ Fetching from table: ${tableName}`);

    // Check if table exists
    const tableCheck = await pool.query(
      `SELECT EXISTS (
        SELECT FROM information_schema.tables 
        WHERE table_schema = 'public' 
        AND table_name = $1
      )`,
      [tableName]
    );

    if (!tableCheck.rows[0].exists) {
      console.log(`❌ Table ${tableName} does not exist`);
      return res.status(404).json({
        success: false,
        message: `Table ${tableName} not found`
      });
    }

    // ✅ Build column list dynamically — remark tables don't have StartIndex/StopIndex
    const optionalCols = ['StartIndex', 'StopIndex'];
    const colResult = await pool.query(
      `SELECT column_name FROM information_schema.columns
       WHERE table_schema = 'public'
         AND table_name = $1
         AND column_name = ANY($2)`,
      [tableName, optionalCols]
    );
    const presentCols = new Set(colResult.rows.map((r: any) => r.column_name));

    const selectCols = ['"Id"', '"Title"'];
    if (presentCols.has('StartIndex')) selectCols.push('"StartIndex"');
    if (presentCols.has('StopIndex'))  selectCols.push('"StopIndex"');

    let query = `SELECT ${selectCols.join(', ')} FROM "${tableName}"`;

    // Soft-delete filter
    const columnCheck = await pool.query(
      `SELECT EXISTS (
        SELECT FROM information_schema.columns 
        WHERE table_schema = 'public' 
        AND table_name = $1 
        AND column_name = 'Deleted'
      )`,
      [tableName]
    );

    if (columnCheck.rows[0].exists) {
      query += ` WHERE "Deleted" = false`;
    }
    query += ` ORDER BY "Id"`;

    const result = await pool.query(query);
    console.log(`✅ Found ${result.rows.length} records in ${tableName}`);

    res.json(result.rows);
  } catch (error) {
    console.error('Error fetching lookup values:', error);
    res.status(500).json({ 
      success: false, 
      message: 'Internal server error' 
    });
  }
};
// ==================== UPDATE FUNCTIONS ====================

// Update field findings
export const updateFieldFindings = async (req: Request, res: Response) => {
  try {
    const pool = await poolPromise;
    const { id } = req.params;
    const userId = (req as any).user?.userId || 1;
    const now = new Date();

    // Whitelist of editable columns
    const EDITABLE = new Set([
      'Weight', 'Height', 'Waist', 'Hip',
      'Systolic', 'Diastolic',
      'BPRemarkId', 'RBSValue', 'RBSRemarkId',
      'ReferralIds', // handled separately
    ]);

    // Normalize + whitelist
    const body: Record<string, any> = {};
    for (const [k, v] of Object.entries(req.body)) {
      if (EDITABLE.has(k)) body[k] = v;
    }

    // Fetch current row for recomputation + gender/category sanity
    const current = await pool.query(
      `SELECT t.*, c."GenderId", c."CategoryId"
       FROM "Tallies" t
       JOIN "Clients" c ON t."ClientId" = c."Id"
       WHERE t."Id" = $1 AND t."Deleted" = false`,
      [id]
    );
    if (current.rows.length === 0) {
      return res.status(404).json({ success: false, message: 'Field findings not found' });
    }
    const cur = current.rows[0];

    // Compute updated values
    const weight = body.Weight !== undefined ? Number(body.Weight) : Number(cur.Weight);
    const height = body.Height !== undefined ? Number(body.Height) : Number(cur.Height);
    const waist = body.Waist !== undefined ? Number(body.Waist) : Number(cur.Waist);
    const hip = body.Hip !== undefined ? Number(body.Hip) : Number(cur.Hip);
    const systolic = body.Systolic !== undefined ? Number(body.Systolic) : Number(cur.Systolic);
    const diastolic = body.Diastolic !== undefined ? Number(body.Diastolic) : Number(cur.Diastolic);
    const rbsValue = body.RBSValue !== undefined ? Number(body.RBSValue) : Number(cur.RBSValue);
    const bpRemarkId = body.BPRemarkId !== undefined ? body.BPRemarkId : cur.BPRemarkId;
    const rbsRemarkId = body.RBSRemarkId !== undefined ? body.RBSRemarkId : cur.RBSRemarkId;

    // Recompute derived + interpretation FKs
    const bmi = (weight && height) ? weight / ((height / 100) ** 2) : 0;
    const whr = (waist && hip && hip > 0) ? waist / hip : 0;

    const [bmiHit, bpHit, rbsHit] = await Promise.all([
      interpretValue(pool, 'bmi', bmi),
      interpretValue(pool, 'bp', diastolic),
      interpretValue(pool, 'rbs', rbsValue),
    ]);

    const BMIINTValueId = bmiHit?.Id ?? 6;
    const BPINTValueId  = bpHit?.Id  ?? 6;
    const RBSINTValueId = rbsHit?.Id ?? 5;

    // Update Tallies
    await pool.query(
      `UPDATE "Tallies" SET
        "Weight" = $1, "Height" = $2, "BMIValue" = $3, "BMIINTValueId" = $4,
        "Waist" = $5, "Hip" = $6, "WHRatio" = $7,
        "Systolic" = $8, "Diastolic" = $9, "BPINTValueId" = $10,
        "BPRemarkId" = $11,
        "RBSValue" = $12, "RBSINTValueId" = $13, "RBSRemarkId" = $14,
        "UpdatedOn" = $15
       WHERE "Id" = $16`,
      [
        weight, height, bmi, BMIINTValueId,
        waist, hip, whr,
        systolic, diastolic, BPINTValueId,
        bpRemarkId,
        rbsValue, RBSINTValueId, rbsRemarkId,
        now, id,
      ]
    );

    // Update referral join table if ReferralIds was provided
    if (Array.isArray(body.ReferralIds)) {
      const referralIds: number[] = body.ReferralIds
        .map(Number)
        .filter((n: number) => Number.isFinite(n) && n > 0);

      await pool.query(`DELETE FROM "TallyReferrals" WHERE "TallyId" = $1`, [id]);

      if (referralIds.length > 0) {
        const placeholders = referralIds.map((_, i) => `($1, $${i + 2})`).join(', ');
        await pool.query(
          `INSERT INTO "TallyReferrals" ("TallyId", "ReferralId") VALUES ${placeholders}
           ON CONFLICT ("TallyId", "ReferralId") DO NOTHING`,
          [id, ...referralIds]
        );
      }
    }

    await auditLog(
      userId,
      'FIELD_FINDINGS_UPDATED',
      'Tallies',
      id,
      null,
      { ...body, recomputed: { bmi, whr, BMIINTValueId, BPINTValueId, RBSINTValueId } },
      getClientIp(req),
      getUserAgent(req)
    );

    res.json({ success: true, message: 'Field findings updated', Id: id });
  } catch (error) {
    console.error('Error updating field findings:', error);
    res.status(500).json({ success: false, message: 'Internal server error' });
  }
};

// Update lab findings
export const updateLabFindings = async (req: Request, res: Response) => {
  try {
    const pool = await poolPromise;
    const { id } = req.params;
    const userId = (req as any).user?.userId || 1;
    const now = new Date();

    // Whitelist — lab tech can only touch clinical values, never FKs to user/client
    const EDITABLE = new Set([
      'FBSValue', 'HBA1CValue', 'LipidId',
      'MicroalbuminValue', 'BMDValue', 'PSAValue',
      'HepatitisBValueId', 'HepatitisCValueId',
    ]);

    const body: Record<string, any> = {};
    for (const [k, v] of Object.entries(req.body)) {
      if (EDITABLE.has(k)) body[k] = v;
    }

    const current = await pool.query(
      `SELECT * FROM "Findings" WHERE "Id" = $1 AND "Deleted" = false`,
      [id]
    );
    if (current.rows.length === 0) {
      return res.status(404).json({ success: false, message: 'Lab findings not found' });
    }
    const cur = current.rows[0];

    const num = (v: any, fallback: number) => {
      if (v === undefined || v === null || v === '') return fallback;
      const n = parseFloat(v);
      return Number.isFinite(n) ? n : fallback;
    };
    const toFk = (v: any, fallback: number | null): number | null => {
      if (v === undefined) return fallback;
      if (v === null || v === '') return null;
      const n = parseInt(v);
      return Number.isFinite(n) && n > 0 ? n : null;
    };

    const FBSValue           = num(body.FBSValue,           Number(cur.FBSValue)           || 0);
    const HBA1CValue         = num(body.HBA1CValue,         Number(cur.HBA1CValue)         || 0);
    const MicroalbuminValue  = num(body.MicroalbuminValue,  Number(cur.MicroalbuminValue)  || 0);
    const BMDValue           = num(body.BMDValue,           Number(cur.BMDValue)           || 0);
    const PSAValue           = num(body.PSAValue,           Number(cur.PSAValue)           || 0);
    const LipidId            = toFk(body.LipidId,            cur.LipidId);
    const HepatitisBValueId  = toFk(body.HepatitisBValueId,  cur.HepatitisBValueId);
    const HepatitisCValueId  = toFk(body.HepatitisCValueId,  cur.HepatitisCValueId);

    // Recompute interpretations server-side — single source of truth
    const [fbsHit, hba1cHit, microalbuminHit, psaHit, bmdHit] = await Promise.all([
      interpretValue(pool, 'fbs',          FBSValue),
      interpretValue(pool, 'hba1c',        HBA1CValue),
      interpretValue(pool, 'microalbumin', MicroalbuminValue),
      interpretValue(pool, 'psa',          PSAValue),
      interpretValue(pool, 'bmd',          BMDValue, { allowNegative: true }),
    ]);

    const FBSINTValueId          = fbsHit?.Id          ?? null;
    const HBA1CINTValueId        = hba1cHit?.Id        ?? null;
    const MicroalbuminINTValueId = microalbuminHit?.Id ?? null;
    const PSAINTValueId          = psaHit?.Id          ?? null;
    const BMDINTValueId          = bmdHit?.Id          ?? null;

    await pool.query(
      `UPDATE "Findings" SET
        "FBSValue" = $1,           "FBSINTValueId" = $2,
        "HBA1CValue" = $3,         "HBA1CINTValueId" = $4,
        "LipidId" = $5,
        "MicroalbuminValue" = $6,  "MicroalbuminINTValueId" = $7,
        "BMDValue" = $8,           "BMDINTValueId" = $9,
        "PSAValue" = $10,          "PSAINTValueId" = $11,
        "HepatitisBValueId" = $12, "HepatitisCValueId" = $13,
        "UpdatedOn" = $14
       WHERE "Id" = $15`,
      [
        FBSValue, FBSINTValueId,
        HBA1CValue, HBA1CINTValueId,
        LipidId,
        MicroalbuminValue, MicroalbuminINTValueId,
        BMDValue, BMDINTValueId,
        PSAValue, PSAINTValueId,
        HepatitisBValueId, HepatitisCValueId,
        now, id,
      ]
    );

    await auditLog(
      userId,
      'LAB_FINDINGS_UPDATED',
      'Findings',
      id,
      null,
      { ...body, recomputed: { FBSINTValueId, HBA1CINTValueId, MicroalbuminINTValueId, PSAINTValueId, BMDINTValueId } },
      getClientIp(req),
      getUserAgent(req)
    );

    res.json({ success: true, message: 'Lab findings updated', Id: id });
  } catch (error) {
    console.error('Error updating lab findings:', error);
    res.status(500).json({ success: false, message: 'Internal server error' });
  }
};

